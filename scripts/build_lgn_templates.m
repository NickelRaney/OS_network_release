function out = flip_0(y)
out = y;
out(:, 2:2:end) = 6 - out(:, 2:2:end);
end

function out = flip_45(y)
out = y;
out(:, 1:2:end) = 6 - y(:, 2:2:end);
out(:, 2:2:end) = 6 - y(:, 1:2:end);
end

function out = rot_90(y)
out = y;
out(:, 2:2:end) = 6 - y(:, 1:2:end);
out(:, 1:2:end) = y(:, 2:2:end);
end
